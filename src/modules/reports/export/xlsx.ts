import { crc32, deflateRawSync } from 'node:zlib';
import type { Cell } from './csv.js';

/**
 * Minimal single-sheet XLSX writer (inline strings, numbers, bold header). Small enough to own
 * rather than pull in a spreadsheet library for one flat table.
 */
const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);
/** XML 1.0 forbids most control characters; a stray one would make Excel refuse the whole file. */
const clean = (s: string) => [...s].filter((ch) => ch >= ' ' || ch === '\t' || ch === '\n' || ch === '\r').join('');

function colName(i: number): string {
  let s = '';
  for (let n = i + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s;
  return s;
}

function sheetXml(header: string[], rows: Cell[][]): string {
  const cell = (v: Cell, r: number, c: number, style: number) => {
    const ref = `${colName(c)}${r}`;
    if (v === null || v === '') return '';
    if (typeof v === 'number' && Number.isFinite(v)) return `<c r="${ref}" s="${style}"><v>${v}</v></c>`;
    return `<c r="${ref}" s="${style}" t="inlineStr"><is><t xml:space="preserve">${esc(clean(String(v)))}</t></is></c>`;
  };
  const all = [header as Cell[], ...rows];
  const body = all.map((r, i) => `<row r="${i + 1}">${r.map((v, c) => cell(v, i + 1, c, i === 0 ? 1 : 0)).join('')}</row>`).join('');
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews><sheetData>${body}</sheetData></worksheet>`;
}

